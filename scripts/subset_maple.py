"""Generate Plotip's CJK WOFF2 shards from official Maple Mono CN v7.9 TTFs.

uv run scripts/subset_maple.py --source-dir /path/to/MapleMono-CN-unhinted
No downloads or font generation run during the application build.
"""

import argparse
import hashlib
import json
import subprocess
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "web/public/fonts"
SOURCES = {
    "Regular": "0fcc5139bfd5ab14ff989bb7dfd5236d0cafc10e60b9828569e6883613ab4085",
    "Medium": "fee9d51498dfcba0921494ac774ad9a374021cf45cfcdf33188ce6421b90c050",
    "SemiBold": "96ed7ae26ee7c50b02b2d2b2bc0f1a0cbabe45ae5d6e6abf6678e2177c415677",
    "Bold": "ca79870485fb382e01f4e70edb08bccd3cf1dbdf74b82023fdf2f0c95db55725",
}


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def unicode_ranges(points):
    groups = []
    for point in sorted(points):
        if groups and point == groups[-1][1] + 1:
            groups[-1][1] = point
        else:
            groups.append([point, point])
    return ",".join(f"U+{a:X}" + (f"-{b:X}" if a != b else "") for a, b in groups)


parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--source-dir", type=Path, required=True)
args = parser.parse_args()
latin = OUT / "maple-latin.woff2"
assert digest(latin) == "e7080ef37fa8b3a38f71446e53e546634c27ce2cfe97673478cafc029d6344ee"
latin_font = TTFont(latin)
assert latin_font["name"].getDebugName(5) == "Version 7.900"
assert [(a.axisTag, a.minValue, a.maxValue) for a in latin_font["fvar"].axes] == [
    ("wght", 100, 800)
]
latin_points = set(latin_font.getBestCmap())
ui_paths = sorted((ROOT / "web/src").glob("*.ts")) + [ROOT / "web/index.html"]
data_paths = [
    ROOT / "web/public/world.geojson",
    ROOT / "web/public/regions.geojson",
    ROOT / "data/places.json",
]
# Map labels and result country names also use the browser's localized names.
country_names = subprocess.check_output(
    ["node", "--input-type=module", "-e", """
import fs from 'node:fs';
const world = JSON.parse(fs.readFileSync('web/public/world.geojson'));
const names = new Intl.DisplayNames(['zh'], {type:'region'});
console.log(world.features.map(f => {
  try { return names.of(f.properties.code); } catch { return ''; }
}).join(''));
"""], cwd=ROOT, text=True,
)
ui_chars = set(map(ord, country_names + "".join(p.read_text() for p in ui_paths)))
all_chars = ui_chars | set(map(ord, "".join(p.read_text() for p in data_paths)))
requested = {
    c for c in all_chars - latin_points
    if 0x3000 <= c <= 0x30FF or 0x3400 <= c <= 0x9FFF or 0xFF00 <= c <= 0xFFEF
}
available = set(TTFont(args.source_dir / "MapleMono-CN-Regular.ttf").getBestCmap())
points = requested & available
groups = {"ui": points & ui_chars, "places": points - ui_chars}
css = "/* Generated by scripts/subset_maple.py; all faces use network WOFF2. */\n"
css += ("@font-face {font-family:'Maple Mono';font-style:normal;font-weight:100 800;"
        "font-display:swap;src:url('/fonts/maple-latin.woff2') format('woff2');}\n")
files = {latin.name: {"sha256": digest(latin), "bytes": latin.stat().st_size}}
for weight, style in zip([400, 500, 600, 700], SOURCES, strict=True):
    source = args.source_dir / f"MapleMono-CN-{style}.ttf"
    assert digest(source) == SOURCES[style], f"Unexpected official source: {source.name}"
    for group, codes in groups.items():
        font = TTFont(source, recalcTimestamp=False)
        assert font["name"].getDebugName(5) == "Version 7.900"
        assert font["OS/2"].usWeightClass == weight
        assert not codes - set(font.getBestCmap())
        options = subset.Options()
        options.name_IDs = ["*"]
        options.name_legacy = True
        options.name_languages = ["*"]
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=codes)
        subsetter.subset(font)
        font.flavor = "woff2"
        filename = f"maple-cn-{group}-{weight}.woff2"
        font.save(OUT / filename)
        css += (f"@font-face {{font-family:'Maple Mono CN';font-style:normal;"
                f"font-weight:{weight};font-display:swap;"
                f"src:url('/fonts/{filename}') format('woff2');"
                f"unicode-range:{unicode_ranges(codes)};}}\n")
        files[filename] = {"sha256": digest(OUT / filename),
                           "bytes": (OUT / filename).stat().st_size}
(ROOT / "web/src/fonts.css").write_text(css)
manifest = {
    "version": "7.900", "fonttools": "4.68.0",
    "latinSource": "https://github.com/subframe7536/maple-font/blob/v7.9/woff2/var/"
                   "MapleMono%5Bwght%5D-VF.woff2",
    "cnSource": "https://github.com/subframe7536/maple-font/releases/download/v7.9/"
                "MapleMono-CN-unhinted.zip",
    "sourceSha256": {f"MapleMono-CN-{k}.ttf": v for k, v in SOURCES.items()},
    "vocabularySha256": {str(p.relative_to(ROOT)): digest(p) for p in ui_paths + data_paths},
    "intlCountryNames": country_names.strip(),
    "cjkCodepoints": sorted(points), "uiCodepoints": sorted(groups["ui"]),
    "systemFallbackCodepoints": sorted(requested - available), "files": files,
}
(OUT / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
print(json.dumps({"cjkGlyphs": len(points), "uiGlyphs": len(groups["ui"]),
                  "totalBytes": sum(f["bytes"] for f in files.values()),
                  "systemFallbackCodepoints": sorted(requested - available)}))
